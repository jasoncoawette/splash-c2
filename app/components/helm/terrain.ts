/** Metres above sea level at a position, bilinearly sampled; 0 outside the grid. */
export function elevationAt(latitude: number, longitude: number): number {
  const { west, east, south, north, cols, rows, heights } = TERRAIN_GRID;
  if (longitude < west || longitude > east || latitude < south || latitude > north) return 0;

  const fx = ((longitude - west) / (east - west)) * cols - 0.5;
  const fy = ((north - latitude) / (north - south)) * rows - 0.5;
  const x0 = Math.max(0, Math.min(cols - 1, Math.floor(fx)));
  const y0 = Math.max(0, Math.min(rows - 1, Math.floor(fy)));
  const x1 = Math.min(cols - 1, x0 + 1);
  const y1 = Math.min(rows - 1, y0 + 1);
  const tx = Math.max(0, Math.min(1, fx - x0));
  const ty = Math.max(0, Math.min(1, fy - y0));

  const top = heights[y0 * cols + x0] * (1 - tx) + heights[y0 * cols + x1] * tx;
  const bottom = heights[y1 * cols + x0] * (1 - tx) + heights[y1 * cols + x1] * tx;
  return top * (1 - ty) + bottom * ty;
}

export interface HorizonPoint {
  /** Degrees off the camera's centreline, negative to port. */
  relativeDegrees: number;
  /** Degrees above the horizon that the land rises to. */
  angleDegrees: number;
  /** Distance to whatever is making that angle, in nautical miles. */
  distanceNm: number;
}

const METRES_PER_DEGREE_LAT = 110574;
const NM_PER_METRE = 1 / 1852;

/**
 * What the shore looks like from here.
 *
 * For each bearing across the camera's field of view, march outward over the
 * elevation grid and keep the largest angular height found. That is what the
 * eye actually sees: a 400 m ridge ten miles off sits lower in the frame than a
 * 60 m bluff half a mile away, and marching rather than taking the nearest hit
 * is what gets that right.
 */
export function horizonProfile(
  origin: { latitude: number; longitude: number },
  headingDegrees: number,
  fieldOfViewDegrees: number,
  eyeHeightM: number,
  samples = 41,
): HorizonPoint[] {
  const metresPerDegreeLon = METRES_PER_DEGREE_LAT
    * Math.cos((origin.latitude * Math.PI) / 180);
  const profile: HorizonPoint[] = [];

  for (let i = 0; i < samples; i += 1) {
    const relativeDegrees = -fieldOfViewDegrees / 2
      + (i / (samples - 1)) * fieldOfViewDegrees;
    const bearing = ((headingDegrees + relativeDegrees) * Math.PI) / 180;
    const northStep = Math.cos(bearing);
    const eastStep = Math.sin(bearing);

    let angleDegrees = 0;
    let distanceNm = 0;

    // 250 m steps out to 25 km: finer than the grid near the boat, and far
    // enough to reach the hills behind the far shore.
    for (let metres = 250; metres <= 25000; metres += 250) {
      const latitude = origin.latitude + (northStep * metres) / METRES_PER_DEGREE_LAT;
      const longitude = origin.longitude + (eastStep * metres) / metresPerDegreeLon;
      const elevation = elevationAt(latitude, longitude);
      if (elevation <= 0) continue;

      const angle = (Math.atan2(elevation - eyeHeightM, metres) * 180) / Math.PI;
      if (angle <= angleDegrees) continue;

      angleDegrees = angle;
      distanceNm = metres * NM_PER_METRE;
    }

    profile.push({ relativeDegrees, angleDegrees, distanceNm });
  }

  return profile;
}
